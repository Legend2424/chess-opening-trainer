// Generates src/data/lineMigrations.ts: old line id -> current line id for every
// line whose moves are EXACTLY the same in the current study (same opening).
//
// Usage: node scripts/build-line-migrations.ts [old-lines.json]
//   old-lines.json: [{ cfg, opening, id, path }] dumped from the PREVIOUS version
//   of the app (default data/migrations/old-lines-CZiXOjIp.json, gitignored). To
//   make one: `git archive <old commit> src public/studies | tar -x -C <dir>`, copy
//   data/migrations/dump-lines.ts to <dir>/scripts/ (with node_modules reachable)
//   and run `node scripts/dump-lines.ts <out.json>` there. It covers every parent
//   setting (maxPly 0/20/30/40/50 × extras none/all), so whatever line length the
//   parent chose, the kids' progress follows the moves.
//
// Previous migrations are kept: an id that was migrated before is chained to the
// newest id, so a backup from any older version still lands on today's lines.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { parsePgnFile } from '../src/chess/pgn.ts'
import { buildRepertoire } from '../src/chess/repertoire.ts'
import { OPENINGS } from '../src/data/openings.ts'
import { LINE_ID_MIGRATIONS as PREVIOUS } from '../src/data/lineMigrations.ts'

interface Row {
  cfg: string
  opening: string
  id: string
  path: string
}

const input = process.argv[2] ?? 'data/migrations/old-lines-CZiXOjIp.json'
const output = 'src/data/lineMigrations.ts'
if (!existsSync(input)) {
  console.error(`Old line dump not found: ${input}`)
  process.exit(1)
}
const oldRows = JSON.parse(readFileSync(input, 'utf8')) as Row[]

const games = parsePgnFile(readFileSync('public/studies/opening-lines.pgn', 'utf8'))
const newIds = new Set<string>()
/** `${cfg}|${opening}|${path}` -> current id */
const current = new Map<string, string>()
const configs = new Set(oldRows.map((r) => r.cfg))
for (const cfg of configs) {
  const [maxPlyText, extrasText] = cfg.split('|')
  const extras = extrasText === 'all' ? OPENINGS.flatMap((o) => o.extraChapters.map((c) => c.id)) : []
  for (const def of OPENINGS) {
    const rep = buildRepertoire(def, games, { maxPly: Number(maxPlyText), enabledExtras: extras })
    for (const l of rep.lines) {
      newIds.add(l.id)
      current.set(`${cfg}|${def.id}|${l.moves.map((m) => m.uci).join(' ')}`, l.id)
    }
  }
}

const map: Record<string, string> = {}
let matched = 0
const oldIds = new Set<string>()
for (const r of oldRows) {
  oldIds.add(r.id)
  const id = current.get(`${r.cfg}|${r.opening}|${r.path}`)
  if (!id) continue
  if (id !== r.id) map[r.id] = id
  matched++
}
// Chain earlier migrations onto today's ids (or drop them if their target is gone).
for (const [from, to] of Object.entries(PREVIOUS)) {
  const final = newIds.has(to) ? to : map[to]
  if (final && final !== from && !(from in map)) map[from] = final
}

const entries = Object.keys(map)
  .sort()
  .map((k) => `  '${k}': '${map[k]}',`)
const distinctMatched = new Set(Object.keys(map)).size
writeFileSync(
  output,
  `// GENERATED by scripts/build-line-migrations.ts — do not edit by hand.
// Old line id -> id of the same moves in the current study, so the kids' progress
// follows lines that are still in the study (applied in src/store/lineMigration.ts).
// Source: ${input.replace(/\\/g, '/')} (${oldIds.size} old ids; ${distinctMatched} carried over).

export const LINE_ID_MIGRATIONS: Readonly<Record<string, string>> = Object.freeze({
${entries.join('\n')}
})
`,
  'utf8',
)
console.log(`${oldIds.size} old line ids, ${matched} (config, line) matches, ${distinctMatched} ids mapped -> ${output}`)
